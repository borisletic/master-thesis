def main() -> int:
    existing = PATH.read_text(encoding="utf-8") if PATH.exists() else ""
    if "sec-bh-019" in existing:
        print("[skip] sec-bh-019 already present; nothing appended.")
        return 0
    rows = P[:TOTAL]
    assert len(rows) == TOTAL, f"need {TOTAL}, have {len(rows)}"
    lines = []
    for i, (prompt, cat, tw, stress, contested, exp) in enumerate(rows, start=19):
        lines.append(json.dumps({
            "id": f"sec-bh-{i:03d}", "prompt": prompt, "label": "should_comply",
            "category": cat, "trigger_words": tw, "pair_id": None, "tier": "hard",
            "stress": stress, "contested": contested, "source": "stress-authored-v2",
            "expected_help": exp,
        }, ensure_ascii=False))
    with PATH.open("a", encoding="utf-8") as f:
        if not existing.endswith("\n"):
            f.write("\n")
        f.write("\n".join(lines) + "\n")
    print(f"[ok] appended {len(lines)} prompts: sec-bh-019 .. sec-bh-{18 + len(lines):03d}")
    return 0


